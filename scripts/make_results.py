"""Regenerate every table/figure in results/ from the stored CSVs (no models run)."""
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from facedata.dataset.metadata import MetadataStore
from facedata.evaluation import AgeEstimationEvaluator, FairFaceEvaluator, HumanEvalAnalyser
from facedata.evaluation.fairface_eval import NOTEBOOK_MAPPING

ROOT = Path(__file__).resolve().parents[1]
D, OUT = ROOT / "data", ROOT / "results"
FIG = OUT / "figures"
FIG.mkdir(parents=True, exist_ok=True)


def heatmap(table: pd.DataFrame, title: str, path: Path, xlabel: str, ylabel: str, fmt="d"):
    fig, ax = plt.subplots(figsize=(1.0 + 0.9 * table.shape[1], 1.0 + 0.55 * table.shape[0]))
    im = ax.imshow(table.values, cmap="Blues")
    ax.set_xticks(range(table.shape[1]), table.columns, rotation=45, ha="right")
    ax.set_yticks(range(table.shape[0]), table.index)
    for i in range(table.shape[0]):
        for j in range(table.shape[1]):
            v = table.values[i, j]
            ax.text(j, i, format(v, fmt), ha="center", va="center",
                    color="white" if v > table.values.max() * 0.6 else "black", fontsize=8)
    ax.set(title=title, xlabel=xlabel, ylabel=ylabel)
    fig.colorbar(im, ax=ax, shrink=0.8)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def bars(series: pd.Series, title: str, path: Path, ylabel="Accuracy"):
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.bar(series.index.astype(str), series.values, color="#4C78A8")
    for i, v in enumerate(series.values):
        ax.text(i, v + 0.01, f"{v:.2f}", ha="center", fontsize=9)
    ax.set(ylim=(0, 1.08), ylabel=ylabel, title=title)
    plt.setp(ax.get_xticklabels(), rotation=30, ha="right")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


# --- dataset composition -------------------------------------------------
final = MetadataStore.from_csv(D / "metadata/final_dataset_original_labels.csv", validate=False)
ct = final.crosstab()
ct.to_csv(OUT / "dataset_ethnicity_by_age_group.csv")
final.df["gender"].value_counts().rename_axis("gender").to_csv(OUT / "dataset_gender_counts.csv")
heatmap(ct, "Images per ethnicity and age group (n=1,378)", FIG / "dataset_distribution.png", "Age group", "Ethnicity")

# --- FairFace ethnicity ---------------------------------------------------
gt = pd.read_csv(D / "metadata/final_dataset_original_labels.csv")
ff = FairFaceEvaluator.load_predictions(D / "predictions/fairface_test_outputs.csv")
res = FairFaceEvaluator().evaluate(ff, gt)
res.per_group_accuracy.rename("accuracy").to_csv(OUT / "fairface_accuracy_by_group.csv")
res.confusion.to_csv(OUT / "fairface_confusion.csv")
bars(res.per_group_accuracy, f"FairFace agreement with intended ethnicity (overall {res.accuracy:.2f})", FIG / "fairface_accuracy.png")
heatmap(res.confusion, "FairFace: intended vs predicted", FIG / "fairface_confusion.png", "FairFace prediction", "Intended (mapped)")
nb = FairFaceEvaluator(NOTEBOOK_MAPPING).evaluate(ff, gt)

# --- InsightFace age ------------------------------------------------------
age = AgeEstimationEvaluator()
ares = age.evaluate(age.load_predictions(D / "predictions/insightface_predictions.csv"), gt)
ares.per_group.to_csv(OUT / "age_accuracy_by_group.csv")
ares.confusion.to_csv(OUT / "age_confusion.csv")
bars(ares.per_group["accuracy"], f"InsightFace exact age-group accuracy (overall {ares.accuracy:.2f})", FIG / "age_accuracy.png")
heatmap(ares.confusion, "InsightFace: intended vs predicted age group", FIG / "age_confusion.png", "Predicted", "Intended")

# --- Human ratings --------------------------------------------------------
h = HumanEvalAnalyser.from_csv(D / "human_eval/evaluation_results_anonymised.csv")
h.summary().to_csv(OUT / "human_overall.csv", index=False)
h.summary(by="age_group").to_csv(OUT / "human_by_age_group.csv", index=False)
h.summary(by="ethnicity").to_csv(OUT / "human_by_ethnicity.csv", index=False)

# --- Summary -------------------------------------------------------------
lines = [
    "# Results summary (generated by scripts/make_results.py)",
    "",
    f"- Dataset: {len(final.df)} images, {final.df['ethnicity'].nunique()} ethnicity labels, 5 age groups",
    f"- FairFace agreement (all labels mapped): {res.accuracy:.3f} over {res.n_rows} detected faces",
    f"- FairFace agreement with the mapping saved in the notebook: {nb.accuracy:.3f} "
    f"({nb.n_unmapped_dropped} rows dropped, sub-Saharan labels unmapped)",
    f"- InsightFace exact age-group accuracy: {ares.accuracy:.3f}; within one group: {ares.adjacent_accuracy:.3f} "
    f"({ares.n} images with a detected face)",
    "",
    "## InsightFace by intended age group",
    ares.per_group.round(3).to_string(),
    "",
    "## Human ratings (1-5), mean with 95% bootstrap CI",
    h.summary().round(2).to_string(index=False),
]
(OUT / "summary.md").write_text("\n".join(lines), encoding="utf8")
print("\n".join(lines[:8]))
